/*============================================================================
* drv_types.h —— 器件驱动层：公共类型
*
* 层次定位：App → Service → **Driver(器件驱动层)** → BSP → HAL/CMSIS
*
* 为什么单独一个文件：`drv_status_t` 是**整层共用**的返回码（见
* docs_sensor/07-接口约定.md#状态码体系：每层一套、不跨层复用）。它原先定义在
* `drv_sensor.h` 里，第二个驱动（`drv_at24c04`）再引用它就变成了「存储驱动去包含
* 传感器驱动头文件」这种假依赖。这里把它提出来，各器件驱动只依赖本文件。
*
* 本层约定（节选，全文见 07-接口约定#Driver 层）：
*   - 只允许调用 BSP 提供的接口；不得 #include "qpc.h"，不得直接碰寄存器或 HAL
*   - 输出参数放最后、只读入参用 const、返回值只表达成功 / 失败
*   - 允许毫秒级的总线等待但必须带超时；超过毫秒级的等待必须拆成
*     「发起 → 由调用方用事件推进 → 继续」两步（本工程的 AT24C04 就是这么做的）
*===========================================================================*/
#ifndef DRV_TYPES_H
#define DRV_TYPES_H

/* Driver 层状态码（本层专用，不跨层复用） */
typedef enum {
    DRV_OK = 0,      /* 成功                                 */
    DRV_ERR_PARAM,   /* 入参非法                             */
    DRV_ERR_BUS,     /* 总线 / 时序错误                      */
    DRV_ERR_TIMEOUT, /* 操作超时                             */
    DRV_ERR_NODEV,   /* 器件不存在或未初始化                 */
    DRV_ERR_BUSY     /* 上一次作业尚未结束（非阻塞接口需要） */
} drv_status_t;

#endif /* DRV_TYPES_H */
